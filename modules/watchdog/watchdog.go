// Package watchdog is a module that marks the instance Unhealthy when its
// local checks keep failing, so the Auto Scaling group replaces it. It runs
// every WatchCheck of the box (its own Checks and those other modules
// contribute, such as the tunnel's) once per interval; when they have been
// failing for FailMinutes it restarts RestartUnits up to RestartAttempts
// times and then calls autoscaling:SetInstanceHealth. The timer is started
// only on a boot into service, so a warm-pool instance never reports.
//
// The role needs autoscaling:SetInstanceHealth on the box's own group, which
// the appliance grants whenever the box has a launch hook.
package watchdog

import (
	"errors"
	"fmt"
	"regexp"
	"strings"

	"github.com/truvity/asg/bootstrap"
	"github.com/truvity/asg/module"
)

// Defaults.
const (
	DefaultIntervalSeconds  = 60
	DefaultBootDelaySeconds = 120
	DefaultFailMinutes      = 5

	// StartOrder is the order of the step that turns the timer on: after the
	// services it watches were started.
	StartOrder = 900
)

const (
	scriptPath = module.LibDir + "/watchdog.sh"
	confPath   = "/etc/asg/watchdog.conf"
	timerUnit  = "asg-watchdog.timer"
)

var unitRe = regexp.MustCompile(`^[A-Za-z0-9_@:.-]+\.service$`)

// Args configure the watchdog.
type Args struct {
	// Checks are the box's own local checks. Other modules add theirs.
	Checks []module.WatchCheck
	// IntervalSeconds between runs. Default 60.
	IntervalSeconds int
	// BootDelaySeconds is the timer's delay after boot. Default 120.
	BootDelaySeconds int
	// FailMinutes is how long the checks may fail in a row before the
	// watchdog acts. Default 5.
	FailMinutes int
	// RestartUnits (service names) are restarted, up to RestartAttempts
	// times, before the instance is marked Unhealthy. Default none.
	RestartUnits    []string
	RestartAttempts int
}

type mod struct{ a Args }

// New returns the watchdog module.
func New(a Args) module.Module { return mod{a: a} }

func (mod) Name() string { return "watchdog" }

func (m mod) Contribute() (module.Contribution, error) {
	a := m.a
	if a.IntervalSeconds == 0 {
		a.IntervalSeconds = DefaultIntervalSeconds
	}

	if a.BootDelaySeconds == 0 {
		a.BootDelaySeconds = DefaultBootDelaySeconds
	}

	if a.FailMinutes == 0 {
		a.FailMinutes = DefaultFailMinutes
	}

	var errs []error

	if a.IntervalSeconds < 10 || a.BootDelaySeconds < 0 || a.FailMinutes < 1 || a.RestartAttempts < 0 {
		errs = append(errs, fmt.Errorf("want IntervalSeconds >= 10, BootDelaySeconds >= 0, FailMinutes >= 1 and RestartAttempts >= 0 (got %d, %d, %d, %d)",
			a.IntervalSeconds, a.BootDelaySeconds, a.FailMinutes, a.RestartAttempts))
	}

	for _, u := range a.RestartUnits {
		if !unitRe.MatchString(u) {
			errs = append(errs, fmt.Errorf("RestartUnits entry %q: want a service name such as app.service", u))
		}
	}

	if a.RestartAttempts > 0 && len(a.RestartUnits) == 0 {
		errs = append(errs, errors.New("RestartAttempts is set but RestartUnits is empty"))
	}

	if err := errors.Join(errs...); err != nil {
		return module.Contribution{}, err
	}

	conf := fmt.Sprintf("# Rendered by github.com/truvity/asg/modules/watchdog. No secret.\nFAIL_SECONDS=%d\nRESTART_ATTEMPTS=%d\nRESTART_UNITS=(%s)\n",
		a.FailMinutes*60, a.RestartAttempts, quoteAll(a.RestartUnits))

	service := "[Unit]\nDescription=Local health check; marks the instance Unhealthy when it fails for too long\n\n" +
		"[Service]\nType=oneshot\nExecStart=" + scriptPath + "\n"

	// No [Install]: only a boot into service starts the timer.
	timer := fmt.Sprintf("[Unit]\nDescription=Local health check, every %d seconds\n\n[Timer]\nOnBootSec=%ds\nOnUnitActiveSec=%ds\nAccuracySec=1s\n",
		a.IntervalSeconds, a.BootDelaySeconds, a.IntervalSeconds)

	return module.Contribution{
		Fragments: []bootstrap.Fragment{bootstrap.Compose("watchdog",
			bootstrap.File{Path: scriptPath, Mode: "0755", Delivery: bootstrap.DeliveryInline, Content: script},
			bootstrap.File{Path: confPath, Mode: "0644", Delivery: bootstrap.DeliveryInline, Content: conf},
			bootstrap.Unit{Name: "asg-watchdog.service", Content: service},
			bootstrap.Unit{Name: timerUnit, Content: timer},
		)},
		Watch:     a.Checks,
		InService: []module.Step{{Name: "watchdog", Order: StartOrder, Script: "systemctl start " + timerUnit + "\n"}},
	}, nil
}

func quoteAll(in []string) string {
	q := make([]string, len(in))
	for i, s := range in {
		q[i] = module.ShellQuote(s)
	}

	return strings.Join(q, " ")
}

const script = `#!/bin/bash
# asg-watchdog: runs every check in watch.d; once they have been failing for
# FAIL_SECONDS it restarts RESTART_UNITS (up to RESTART_ATTEMPTS times), then
# asks the Auto Scaling group to replace this instance. It is the only
# recovery a stateless box has: Restart=always in the units handles the quick
# failures before that. Generated by github.com/truvity/asg/modules/watchdog.
set -uo pipefail

LIB="${ASG_LIB:-/usr/local/lib/asg}"
STATE="${ASG_WATCHDOG_STATE:-/run/asg-watchdog}"

# shellcheck disable=SC1090
. "${ASG_WATCHDOG_CONF:-/etc/asg/watchdog.conf}"

log() { printf '%s asg-watchdog: %s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" "$*" >&2; }

imds() {
  local t
  t="$(curl -fsS -m 5 -X PUT -H 'X-aws-ec2-metadata-token-ttl-seconds: 300' http://169.254.169.254/latest/api/token)" || return 1
  curl -fsS -m 5 -H "X-aws-ec2-metadata-token: $t" "http://169.254.169.254/latest/meta-data/$1"
}

ok=1
for f in "$LIB"/watch.d/*; do
  [ -e "$f" ] || continue
  bash "$f" >/dev/null 2>&1 || { log "check $(basename "$f") failed"; ok=0; }
done

mkdir -p "$STATE"
if [ "$ok" = 1 ]; then
  rm -f "$STATE/unhealthy-since" "$STATE/restarts"
  exit 0
fi

now="$(date +%s)"
[ -f "$STATE/unhealthy-since" ] || echo "$now" >"$STATE/unhealthy-since"
since="$(cat "$STATE/unhealthy-since")"
log "failing since $since"
[ $((now - since)) -ge "$FAIL_SECONDS" ] || exit 0

restarts="$(cat "$STATE/restarts" 2>/dev/null || echo 0)"
if [ "$restarts" -lt "$RESTART_ATTEMPTS" ] && [ "${#RESTART_UNITS[@]}" -gt 0 ]; then
  restarts=$((restarts + 1))
  echo "$restarts" >"$STATE/restarts"
  echo "$now" >"$STATE/unhealthy-since"
  log "restarting ${RESTART_UNITS[*]} (attempt $restarts of $RESTART_ATTEMPTS)"
  systemctl restart "${RESTART_UNITS[@]}" || log "restart failed"
  exit 0
fi

iid="$(imds instance-id)"
region="$(imds placement/region)"
log "failing for over $((FAIL_SECONDS / 60)) minutes; marking $iid Unhealthy"
aws autoscaling set-instance-health --instance-id "$iid" --health-status Unhealthy --region "$region" || log "set-instance-health failed"
`
